"""Inventory selectable portrait sources from the preserved dfttk build packs."""
import json
from collections import defaultdict
from urllib.parse import urljoin

from sync_dfttk_database import ROOT, assemble, load


def main():
    manifest = load('manifest.json')
    sources = defaultdict(set)
    kinds = {}
    for weapon_id, spec in manifest['weaponPacks'].items():
        kinds[weapon_id] = 'weapon'
        for item_id, record in assemble(spec)['display']['objects'].items():
            if record.get('playerSelectable') or item_id == weapon_id:
                if record.get('imagePath'):
                    sources[item_id].add(urljoin('https://dfttk.com/', record['imagePath']))
    for path in manifest['entrypoints']['library'].values():
        for item_id, record in load(path)['parts'].items():
            if item_id not in kinds:
                kinds[item_id] = 'attachment'
            if record.get('image'):
                sources[item_id].add(urljoin('https://dfttk.com/', record['image']))
    conflicts = {item_id: sorted(urls) for item_id, urls in sources.items() if len(urls) > 1}
    if conflicts:
        raise ValueError(f'Conflicting portrait sources: {conflicts}')
    entries = [dict(id=item_id, kind=kind,
                    source_url=next(iter(sources[item_id]), None),
                    url=next(iter(sources[item_id]), f'https://playerhub.df.qq.com/playerhub/60004/object/{item_id}.png'))
               for item_id, kind in sorted(kinds.items())]
    directory = ROOT / '.scratch/portrait-audit'
    directory.mkdir(parents=True, exist_ok=True)
    (directory / 'inventory.json').write_text(json.dumps(dict(data_version=manifest['dataVersion'], entries=entries), indent=2), 'utf-8')
    # Shared by the picker and current build, so source overrides work before a
    # weapon is selected as well as after its build pack has been loaded.
    asset_directory = ROOT / 'builder/assets'
    asset_directory.mkdir(parents=True, exist_ok=True)
    unavailable_path = asset_directory / 'unavailable-portraits.json'
    unavailable = json.loads(unavailable_path.read_text('utf-8'))['items'] if unavailable_path.exists() else {}
    (asset_directory / 'portraits.js').write_text(
        '// Generated by tools/prepare_portrait_audit.py from preserved dfttk sources.\n'
        + 'export const portraits = ' + json.dumps({entry['id']: None if entry['id'] in unavailable else entry['url'] for entry in entries}, indent=2) + ';\n', 'utf-8')
    print(f'{len(entries)} portraits: {sum(e["kind"] == "weapon" for e in entries)} weapons, {sum(e["kind"] == "attachment" for e in entries)} attachments')


if __name__ == '__main__':
    main()
